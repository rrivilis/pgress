//! Proptest-based invariant suite for pgrs-core.
//!
//! Two axes:
//!
//! ## 1. Property-based invariant tests
//!
//! Each test generates a random ISA op sequence and asserts structural
//! invariants that must hold for every possible execution trace:
//!
//! | Invariant                        | What it catches                          |
//! |----------------------------------|------------------------------------------|
//! | Snapshot/replay equivalence      | Non-determinism, hidden mutable state    |
//! | Version monotonicity             | Stale cache, rollback bugs               |
//! | No dangling edges                | DPO admissibility failures               |
//! | Identity layer stability         | Accidental mutation of id layer (I8)     |
//! | Propagation termination          | Cycle detection / step-limit bugs        |
//! | Causal history monotonicity      | Clock regression                         |
//!
//! ## 2. Adversarial topology tests
//!
//! Fixed deterministic topologies that maximise stress on specific subsystems:
//! dense fan-in, long chains, Zero oscillation, delta-gating idempotency,
//! Bochvar infection across multi-hop chains.

use pgress_core::{
    ComputeRule, Engine, EngineError, ExecMode, IsaOp, NodeKind, PropError, PropEvent, T, Uid,
    uid,
};
use proptest::prelude::*;
use std::collections::HashMap;

// ── Deterministic UID generation ──────────────────────────────────────────────

/// Map a u64 to a deterministic non-nil UUID for use in scripted ops.
/// The high bit is set to push the value into a stable region of the UUID space.
fn uid_from_u64(n: u64) -> Uid {
    // Use from_u128: sets bit 127 so the result is never nil.
    Uid::from_u128((n as u128) | (1u128 << 127))
}

fn arb_uid() -> impl Strategy<Value = Uid> {
    // Ensure non-zero; or-ing 1 forces the LSB set.
    any::<u64>().prop_map(|n| uid_from_u64(n | 1))
}

// ── Script operation types ────────────────────────────────────────────────────

/// Simplified compute rule variants for proptest generation.
#[derive(Debug, Clone, Copy)]
enum CRule {
    Identity,
    MvNeg,
    MvAdd,
    MvMul,
    MeetAll,
    JoinAny,
    BochvarFold,
}

impl CRule {
    fn into_rule(self) -> ComputeRule {
        match self {
            CRule::Identity    => ComputeRule::Identity,
            CRule::MvNeg       => ComputeRule::MvNeg,
            CRule::MvAdd       => ComputeRule::MvAdd,
            CRule::MvMul       => ComputeRule::MvMul,
            CRule::MeetAll     => ComputeRule::MeetAll,
            CRule::JoinAny     => ComputeRule::JoinAny,
            CRule::BochvarFold => ComputeRule::BochvarFold,
        }
    }
}

fn arb_crule() -> impl Strategy<Value = CRule> {
    prop_oneof![
        Just(CRule::Identity),
        Just(CRule::MvNeg),
        Just(CRule::MvAdd),
        Just(CRule::MvMul),
        Just(CRule::MeetAll),
        Just(CRule::JoinAny),
        Just(CRule::BochvarFold),
    ]
}

/// Ternary value variants for proptest.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum TVal { Neg, Zero, Pos }

impl TVal {
    fn into_t(self) -> T {
        match self {
            TVal::Neg  => T::Neg,
            TVal::Zero => T::Zero,
            TVal::Pos  => T::Pos,
        }
    }
}

fn arb_tval() -> impl Strategy<Value = TVal> {
    prop_oneof![
        // Bias toward Pos (the "interesting" case for propagation)
        2 => Just(TVal::Pos),
        1 => Just(TVal::Neg),
        1 => Just(TVal::Zero),
    ]
}

fn arb_emode() -> impl Strategy<Value = ExecMode> {
    prop_oneof![
        // Bias toward Eager (default mode) so most nodes propagate
        3 => Just(ExecMode::Eager),
        1 => Just(ExecMode::Lazy),
        1 => Just(ExecMode::Stabilizing),
    ]
}

/// A scripted ISA operation.
///
/// UIDs are embedded in the op (generated by proptest) so that replay is
/// 100% deterministic — no `uid::fresh()` is called during execution.
/// Slot indices are resolved modulo the current live node/edge count.
#[derive(Debug, Clone)]
enum ScriptOp {
    /// Create an input node with a pre-specified UID.
    CreateInput { id: Uid },
    /// Create a computed node.
    CreateComputed { id: Uid, rule: CRule },
    /// Connect src_slot → tgt_slot (no self-loops).
    Connect { eid: Uid, src_slot: usize, tgt_slot: usize },
    /// Set a node's value.
    SetVal { node_slot: usize, val: TVal },
    /// Flip polarity of a node.
    Reflect { node_slot: usize },
    /// Delete a node (DPO admissibility checked by engine).
    DelNode { node_slot: usize },
    /// Delete an edge.
    DelEdge { edge_slot: usize },
    /// Demand-pull a node.
    Demand { node_slot: usize },
    /// Change execution mode.
    SetMode { node_slot: usize, mode: ExecMode },
    /// Run e-graph stabilization over all Zero nodes.
    Stabilize,
}

fn arb_script_op() -> impl Strategy<Value = ScriptOp> {
    prop_oneof![
        // Creates (40% total): ensures there's usually a non-empty live set
        4 => arb_uid().prop_map(|id| ScriptOp::CreateInput { id }),
        4 => (arb_uid(), arb_crule())
               .prop_map(|(id, rule)| ScriptOp::CreateComputed { id, rule }),
        // Connections (20%)
        4 => (arb_uid(), any::<usize>(), any::<usize>())
               .prop_map(|(eid, s, t)| ScriptOp::Connect { eid, src_slot: s, tgt_slot: t }),
        // Value mutations (25%)
        4 => (any::<usize>(), arb_tval())
               .prop_map(|(n, v)| ScriptOp::SetVal { node_slot: n, val: v }),
        1 => any::<usize>()
               .prop_map(|n| ScriptOp::Reflect { node_slot: n }),
        // Mode changes (5%)
        1 => (any::<usize>(), arb_emode())
               .prop_map(|(n, m)| ScriptOp::SetMode { node_slot: n, mode: m }),
        // Demand (5%)
        1 => any::<usize>()
               .prop_map(|n| ScriptOp::Demand { node_slot: n }),
        // Deletions (4%)
        1 => any::<usize>()
               .prop_map(|n| ScriptOp::DelNode { node_slot: n }),
        1 => any::<usize>()
               .prop_map(|e| ScriptOp::DelEdge { edge_slot: e }),
        // Stabilize (1%)
        1 => Just(ScriptOp::Stabilize),
    ]
}

// ── Script executor ───────────────────────────────────────────────────────────

/// Tracks live nodes and edges so slot indices can be resolved.
#[derive(Default)]
struct Executor {
    live_nodes: Vec<Uid>,
    live_edges: Vec<Uid>,
}

impl Executor {
    fn new() -> Self { Self::default() }

    /// Apply one scripted op. Returns Ok(true) if the op was applied,
    /// Ok(false) if skipped (no live nodes, self-loop, etc.),
    /// Err if the engine returned a non-DPO error.
    fn step(&mut self, engine: &mut Engine, op: &ScriptOp) -> Result<bool, EngineError> {
        match op {
            ScriptOp::CreateInput { id } => {
                if self.live_nodes.contains(id) { return Ok(false); }
                engine.apply(IsaOp::input_node(*id, "input"))?;
                self.live_nodes.push(*id);
                Ok(true)
            }
            ScriptOp::CreateComputed { id, rule } => {
                if self.live_nodes.contains(id) { return Ok(false); }
                engine.apply(IsaOp::computed_node(*id, "comp", rule.into_rule()))?;
                self.live_nodes.push(*id);
                Ok(true)
            }
            ScriptOp::Connect { eid, src_slot, tgt_slot } => {
                let n = self.live_nodes.len();
                if n < 2 || self.live_edges.contains(eid) { return Ok(false); }
                let src = self.live_nodes[src_slot % n];
                let tgt = self.live_nodes[tgt_slot % n];
                if src == tgt { return Ok(false); }   // no self-loops
                match engine.apply(IsaOp::dep_edge(*eid, src, tgt)) {
                    Ok(_) => { self.live_edges.push(*eid); Ok(true) }
                    Err(e) => Err(e),
                }
            }
            ScriptOp::SetVal { node_slot, val } => {
                if self.live_nodes.is_empty() { return Ok(false); }
                let id = self.live_nodes[node_slot % self.live_nodes.len()];
                engine.apply(IsaOp::SetValue { node: id, val: val.into_t() })?;
                Ok(true)
            }
            ScriptOp::Reflect { node_slot } => {
                if self.live_nodes.is_empty() { return Ok(false); }
                let id = self.live_nodes[node_slot % self.live_nodes.len()];
                engine.apply(IsaOp::Reflect { node: id })?;
                Ok(true)
            }
            ScriptOp::DelNode { node_slot } => {
                let n = self.live_nodes.len();
                if n == 0 { return Ok(false); }
                let idx = node_slot % n;
                let id  = self.live_nodes[idx];
                match engine.apply(IsaOp::DelNode { id }) {
                    Ok(_) => {
                        self.live_nodes.remove(idx);
                        // Engine already removed incident edges; sync our tracker.
                        self.live_edges.retain(|&eid| engine.graph.edge(eid).is_some());
                        Ok(true)
                    }
                    Err(EngineError::DpoViolation(..)) => Ok(false), // expected
                    Err(e) => Err(e),
                }
            }
            ScriptOp::DelEdge { edge_slot } => {
                let n = self.live_edges.len();
                if n == 0 { return Ok(false); }
                let idx = edge_slot % n;
                let eid = self.live_edges[idx];
                match engine.apply(IsaOp::DelEdge { id: eid }) {
                    Ok(_) => { self.live_edges.remove(idx); Ok(true) }
                    Err(EngineError::DpoViolation(..)) => Ok(false),
                    Err(e) => Err(e),
                }
            }
            ScriptOp::Demand { node_slot } => {
                if self.live_nodes.is_empty() { return Ok(false); }
                let id = self.live_nodes[node_slot % self.live_nodes.len()];
                engine.apply(IsaOp::Demand { node: id })?;
                Ok(true)
            }
            ScriptOp::SetMode { node_slot, mode } => {
                if self.live_nodes.is_empty() { return Ok(false); }
                let id = self.live_nodes[node_slot % self.live_nodes.len()];
                engine.apply(IsaOp::SetMode { node: id, mode: *mode })?;
                Ok(true)
            }
            ScriptOp::Stabilize => {
                engine.apply(IsaOp::Stabilize { region: None })?;
                Ok(true)
            }
        }
    }
}

// ── Engine snapshot (for deterministic comparison) ────────────────────────────

/// A stable representation of engine state that can be compared across replay runs.
#[derive(Debug, PartialEq, Eq)]
struct NodeSnap {
    id:      Uid,
    value:   T,
    version: u64,
    typ:     String,
}

#[derive(Debug, PartialEq, Eq)]
struct EngineSnap {
    /// Node states sorted by UID (stable order for eq comparison).
    nodes:      Vec<NodeSnap>,
    edge_count: usize,
}

impl EngineSnap {
    fn capture(engine: &Engine, live: &[Uid]) -> Self {
        let mut nodes: Vec<NodeSnap> = live.iter()
            .filter_map(|&id| {
                engine.graph.node(id).map(|n| NodeSnap {
                    id,
                    value:   n.value,
                    version: n.version,
                    typ:     n.typ.clone(),
                })
            })
            .collect();
        nodes.sort_by_key(|n| n.id);
        EngineSnap { nodes, edge_count: engine.edge_count() }
    }
}

/// Run a full script from scratch and return the final snapshot.
fn run_script(ops: &[ScriptOp]) -> EngineSnap {
    let mut engine = Engine::new();
    let mut exec   = Executor::new();
    for op in ops {
        // Propagation errors from cycles are surfaced; others silently skip.
        let _ = exec.step(&mut engine, op);
    }
    EngineSnap::capture(&engine, &exec.live_nodes)
}

// ═══════════════════════════════════════════════════════════════════════════════
// Proptest invariant tests
// ═══════════════════════════════════════════════════════════════════════════════

proptest! {
    // ── I1: Snapshot/Replay Equivalence ───────────────────────────────────────
    //
    // Applying the same op sequence twice (to two independent engines) must
    // produce identical final states. This catches non-determinism from hidden
    // mutable state, non-deterministic iteration order affecting values, etc.
    #[test]
    fn prop_snapshot_replay_equivalence(
        ops in proptest::collection::vec(arb_script_op(), 10..200)
    ) {
        let snap1 = run_script(&ops);
        let snap2 = run_script(&ops);
        prop_assert_eq!(snap1, snap2,
            "snapshot/replay diverged — engine has hidden non-determinism");
    }

    // ── I2: Version Monotonicity ──────────────────────────────────────────────
    //
    // Node interpretation versions must be non-decreasing across all operations.
    // A version can only increase (when value/attrs change) or stay the same
    // (when the value write is a no-op). It must NEVER decrease.
    #[test]
    fn prop_version_monotone(
        ops in proptest::collection::vec(arb_script_op(), 10..300)
    ) {
        let mut engine  = Engine::new();
        let mut exec    = Executor::new();
        let mut version_floor: HashMap<Uid, u64> = HashMap::new();

        for op in &ops {
            let _ = exec.step(&mut engine, op);

            for &id in &exec.live_nodes {
                if let Some(n) = engine.graph.node(id) {
                    let floor = version_floor.entry(id).or_insert(n.version);
                    prop_assert!(
                        n.version >= *floor,
                        "version decreased for node {:?}: was {}, now {}",
                        id, *floor, n.version
                    );
                    *floor = n.version;
                }
            }
        }
    }

    // ── I3: No Dangling Edges ─────────────────────────────────────────────────
    //
    // After every ISA operation, every edge in the graph must reference nodes
    // that actually exist. The DPO step in DelNode removes incident edges first,
    // so no dangling edge should ever survive.
    #[test]
    fn prop_no_dangling_edges(
        ops in proptest::collection::vec(arb_script_op(), 10..300)
    ) {
        let mut engine = Engine::new();
        let mut exec   = Executor::new();

        for op in &ops {
            let _ = exec.step(&mut engine, op);

            for (_, edge) in &engine.graph.edges {
                prop_assert!(
                    engine.graph.node(edge.src).is_some(),
                    "dangling source on edge {:?} → src {:?} not in graph",
                    edge.id, edge.src
                );
                prop_assert!(
                    engine.graph.node(edge.tgt).is_some(),
                    "dangling target on edge {:?} → tgt {:?} not in graph",
                    edge.id, edge.tgt
                );
            }
        }
    }

    // ── I4: Identity Layer Stability ──────────────────────────────────────────
    //
    // A node's identity-layer fields (`typ`, kind class) must be immutable after
    // creation. SetValue, Reflect, Propagate, Demand all touch only the
    // interpretation layer. The identity layer must never change after NodeCreate.
    #[test]
    fn prop_identity_layer_stable(
        ops in proptest::collection::vec(arb_script_op(), 10..300)
    ) {
        let mut engine    = Engine::new();
        let mut exec      = Executor::new();
        // (typ, is_input) recorded at creation time
        let mut identity: HashMap<Uid, (String, bool)> = HashMap::new();

        for op in &ops {
            // Capture identity before step for creates
            let created_id: Option<(Uid, bool)> = match op {
                ScriptOp::CreateInput   { id }       => Some((*id, true)),
                ScriptOp::CreateComputed { id, .. }  => Some((*id, false)),
                _                                    => None,
            };

            let _ = exec.step(&mut engine, op);

            // Record identity right after creation
            if let Some((id, is_input)) = created_id {
                if let Some(n) = engine.graph.node(id) {
                    identity.insert(id, (n.typ.clone(), is_input));
                }
            }

            // Verify surviving nodes haven't had their identity mutated
            for &id in &exec.live_nodes {
                if let Some(n) = engine.graph.node(id) {
                    if let Some((typ, is_input)) = identity.get(&id) {
                        prop_assert_eq!(
                            &n.typ, typ,
                            "typ mutated for node {:?}", id
                        );
                        let actually_input = matches!(n.kind, NodeKind::Input);
                        prop_assert_eq!(
                            actually_input, *is_input,
                            "kind class changed for node {:?}", id
                        );
                    }
                }
            }
        }
    }

    // ── I6: Causal History Monotonicity ───────────────────────────────────────
    //
    // Every event appended to engine.history must have a strictly increasing
    // `arrival` counter. The causal timestamps must also be non-decreasing
    // (they advance per ISA primitive class, so adjacent ops in the same
    // dimension advance together).
    #[test]
    fn prop_causal_history_monotone(
        ops in proptest::collection::vec(arb_script_op(), 10..200)
    ) {
        let mut engine = Engine::new();
        let mut exec   = Executor::new();
        let mut last_arrival: u64 = 0;

        for op in &ops {
            let history_before = engine.history.len();
            let _ = exec.step(&mut engine, op);

            for ev in &engine.history[history_before..] {
                prop_assert!(
                    ev.stamp.arrival > last_arrival,
                    "arrival counter did not strictly increase: {} after {}",
                    ev.stamp.arrival, last_arrival
                );
                last_arrival = ev.stamp.arrival;
            }
        }
    }
}

// ── I5: Propagation Termination (separate block — reduced case count) ─────────
//
// Push propagation always terminates: values only increase (Neg→Pos, Neg→Zero)
// and the engine skips downstream pushes when the output value is unchanged.
// So even cyclic dep graphs reach a fixed point.
//
// Demand on a cyclic dep graph CAN legitimately hit the step limit — the
// step limit IS the correct termination mechanism for demand cycles. We
// verify that:
//   a) The only error ever returned is Prop(StepLimitExceeded), never a panic.
//   b) After any such error, the engine is still queriable (not corrupted).
//
// We do NOT treat StepLimitExceeded as a failure here: it's an expected and
// handled outcome for demand on cyclic topologies.
//
// Capped at 64 cases / 150 ops: Stabilize calls run full e-graph saturation
// (egg + rewrite rules) which is slow in unoptimised debug builds. This budget
// keeps CI fast while still providing meaningful coverage.
proptest! {
    #![proptest_config(ProptestConfig { cases: 64, ..Default::default() })]

    #[test]
    fn prop_propagation_terminates(
        ops in proptest::collection::vec(arb_script_op(), 5..150)
    ) {
        let mut engine = Engine::new();
        let mut exec   = Executor::new();

        for op in &ops {
            match exec.step(&mut engine, op) {
                // StepLimitExceeded is the correct handled outcome for cyclic
                // demand chains — the engine caught and bounded the cycle.
                // This is NOT a bug; verify the engine is still consistent.
                Err(EngineError::Prop(PropError::StepLimitExceeded(_))) => {
                    // Engine should still be queriable after a bounded error
                    for &id in &exec.live_nodes {
                        let _ = engine.value_of(id); // must not panic
                    }
                }
                // Any other error variant is unexpected and should fail
                Err(other) => {
                    prop_assert!(
                        false,
                        "unexpected engine error (not StepLimitExceeded): {:?}", other
                    );
                }
                Ok(_) => {}
            }
        }
    }
}

